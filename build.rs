//! Embeds the Windows resources: app icon (assets/diskscope.ico), application manifest
//! (assets/diskscope.manifest) and version info.
//!
//! Uses rc.exe from the Windows SDK (installed with the MSVC build tools, which linking needs
//! anyway) and hands the compiled .res straight to link.exe. No build-dependencies. If rc.exe
//! cannot be found or fails, the build goes on without the resources and prints a cargo warning;
//! set the RC environment variable to rc.exe's full path to point it somewhere else.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=assets/diskscope.ico");
    println!("cargo:rerun-if-changed=assets/diskscope.manifest");
    println!("cargo:rerun-if-env-changed=RC");

    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let target_env = env::var("CARGO_CFG_TARGET_ENV").unwrap_or_default();
    if target_os != "windows" {
        return;
    }
    if target_env != "msvc" {
        println!("cargo:warning=diskscope: icon and manifest are only embedded for MSVC targets; skipped");
        return;
    }
    if let Err(e) = embed() {
        println!("cargo:warning=diskscope: icon and manifest not embedded: {e}");
    }
}

fn embed() -> Result<(), String> {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").map_err(|e| e.to_string())?);
    let out_dir = PathBuf::from(env::var("OUT_DIR").map_err(|e| e.to_string())?);
    let assets = manifest_dir.join("assets");
    let icon = assets.join("diskscope.ico");
    let manifest = assets.join("diskscope.manifest");
    for f in [&icon, &manifest] {
        if !f.is_file() {
            return Err(format!("{} is missing", f.display()));
        }
    }

    let rc_exe = find_rc().ok_or("rc.exe not found (install the Windows SDK or set RC)")?;
    let rc_file = out_dir.join("diskscope.rc");
    let res_file = out_dir.join("diskscope.res");
    fs::write(&rc_file, rc_source(&icon, &manifest)).map_err(|e| e.to_string())?;

    let out = Command::new(&rc_exe)
        .arg("/nologo")
        .arg("/fo")
        .arg(&res_file)
        .arg(&rc_file)
        .output()
        .map_err(|e| format!("could not run {}: {e}", rc_exe.display()))?;
    if !out.status.success() {
        let text = String::from_utf8_lossy(&out.stdout).to_string() + &String::from_utf8_lossy(&out.stderr);
        return Err(format!("{} failed: {}", rc_exe.display(), text.trim().replace('\n', " | ")));
    }
    // link.exe takes a .res as an input file and converts it itself.
    println!("cargo:rustc-link-arg-bins={}", res_file.display());
    Ok(())
}

fn rc_source(icon: &Path, manifest: &Path) -> String {
    let v = |k: &str| env::var(k).unwrap_or_else(|_| "0".into());
    let (major, minor, patch) = (v("CARGO_PKG_VERSION_MAJOR"), v("CARGO_PKG_VERSION_MINOR"), v("CARGO_PKG_VERSION_PATCH"));
    let version = env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "0.0.0".into());
    let esc = |p: &Path| p.display().to_string().replace('\\', "\\\\");
    format!(
        r#"// generated by build.rs
1 ICON "{icon}"
1 24 "{manifest}"

1 VERSIONINFO
FILEVERSION {major},{minor},{patch},0
PRODUCTVERSION {major},{minor},{patch},0
FILEFLAGSMASK 0x3F
FILEFLAGS 0x0
FILEOS 0x40004
FILETYPE 0x1
FILESUBTYPE 0x0
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904B0"
    BEGIN
      VALUE "FileDescription", "Diskscope"
      VALUE "FileVersion", "{version}"
      VALUE "InternalName", "diskscope"
      VALUE "OriginalFilename", "diskscope.exe"
      VALUE "ProductName", "Diskscope"
      VALUE "ProductVersion", "{version}"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
"#,
        icon = esc(icon),
        manifest = esc(manifest),
    )
}

/// rc.exe: $RC, then PATH, then the newest Windows 10/11 SDK under Program Files.
fn find_rc() -> Option<PathBuf> {
    if let Some(p) = env::var_os("RC").map(PathBuf::from) {
        if p.is_file() {
            return Some(p);
        }
    }
    if let Some(path) = env::var_os("PATH") {
        for dir in env::split_paths(&path) {
            let p = dir.join("rc.exe");
            if p.is_file() {
                return Some(p);
            }
        }
    }
    let arch = match env::var("HOST").unwrap_or_default().split('-').next() {
        Some("x86_64") => "x64",
        Some("aarch64") => "arm64",
        _ => "x86",
    };
    let mut roots: Vec<PathBuf> = Vec::new();
    if let Some(dir) = env::var_os("WindowsSdkVerBinPath") {
        roots.push(PathBuf::from(dir));
    }
    for var in ["ProgramFiles(x86)", "ProgramFiles"] {
        if let Some(pf) = env::var_os(var) {
            let bin = PathBuf::from(pf).join("Windows Kits").join("10").join("bin");
            // versioned folders (10.0.26100.0, ...), newest first, then the old flat layout
            let mut versions: Vec<(Vec<u32>, PathBuf)> = fs::read_dir(&bin)
                .into_iter()
                .flatten()
                .flatten()
                .filter_map(|e| {
                    let name = e.file_name().to_string_lossy().to_string();
                    let key: Option<Vec<u32>> = name.split('.').map(|s| s.parse().ok()).collect();
                    key.map(|k| (k, e.path()))
                })
                .collect();
            versions.sort_by(|a, b| b.0.cmp(&a.0));
            roots.extend(versions.into_iter().map(|(_, p)| p));
            roots.push(bin);
        }
    }
    for root in roots {
        for a in [arch, "x86"] {
            let p = root.join(a).join("rc.exe");
            if p.is_file() {
                return Some(p);
            }
        }
    }
    None
}
